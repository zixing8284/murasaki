/**
 * Parses a Windows .theme file (or raw `[Control Panel\Colors]` INI section)
 * and returns a map of CSS variable names → hex color strings.
 */
export function parseThemeFile(content: string): Record<string, string> {
  const colors: Record<string, string> = {}

  // Extract lines from [Control Panel\Colors] section, or treat whole input as INI lines
  const colorsSection = extractColorsSection(content)
  const lines = colorsSection.split('\n')

  for (const line of lines) {
    const match = line.match(
      /^\s*([A-Z]+)\s*=\s*((?:[1-9]|1\d|2[0-4])?\d|25[0-5])\s+((?:[1-9]|1\d|2[0-4])?\d|25[0-5])\s+((?:[1-9]|1\d|2[0-4])?\d|25[0-5])\s*$/i,
    )
    if (!match)
      continue

    const themeName = match[1]
    const r = Number(match[2])
    const g = Number(match[3])
    const b = Number(match[4])

    const cssName = THEME_TO_CSS[themeName]
    if (cssName) {
      colors[cssName] = `#${[r, g, b].map(c => c.toString(16).padStart(2, '0')).join('')}`
    }
  }

  return colors
}

function extractColorsSection(content: string): string {
  const lines = content.split(/\r?\n/)
  const sectionLines: string[] = []
  let inColorsSection = false

  for (const line of lines) {
    const trimmed = line.trim()

    if (trimmed.startsWith('[') && trimmed.endsWith(']')) {
      if (trimmed.toLowerCase() === '[control panel\\colors]') {
        inColorsSection = true
        continue
      }

      if (inColorsSection)
        break
    }

    if (inColorsSection)
      sectionLines.push(line)
  }

  if (inColorsSection)
    return sectionLines.join('\n')

  // Fallback: treat entire content as INI color lines
  return content
}

